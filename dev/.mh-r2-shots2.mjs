import { chromium } from 'playwright'; import fs from 'node:fs';
const OUT = process.argv[2]; const exe = fs.existsSync('/opt/pw-browsers/chromium') ? '/opt/pw-browsers/chromium' : undefined;
const b = await chromium.launch({ executablePath: exe });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
const p = await ctx.newPage(); await p.addInitScript(() => { try { sessionStorage.setItem('sf:intro-seen', '1'); } catch {} });
await p.goto('http://127.0.0.1:9331/collections/all'); await p.waitForLoadState('networkidle');
await p.locator('header button[aria-controls*="menu" i], header [data-sf-menu-open], header button[aria-label*="menu" i]').first().click();
await p.waitForTimeout(800);
await p.locator('summary.sf-menu__link:visible').first().click();
await p.waitForTimeout(1200); await p.waitForLoadState('networkidle');
await p.screenshot({ path: `${OUT}/m-menu-shop.png` });
const imgs = await p.evaluate(() => [...document.images].filter((i) => i.getBoundingClientRect().width > 0).map((i) => i.currentSrc.replace(location.origin, '')));
console.log(JSON.stringify(imgs.filter((s) => !/logo/.test(s))));
await b.close();
